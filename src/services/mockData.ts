export function createBlankSOAPNote(consultationId: string, patient: Patient, doctor: Doctor): SOAPNote {
  return {
    id: `note-${consultationId}`,
    consultationId,
    patientId: patient.id,
    doctorId: doctor.id,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    status: 'review_required',
    templateType: 'General Medical SOAP',
    subjective: {
      chiefComplaint: patient.condition || 'Clinical evaluation and routine checkup',
      historyOfPresentIllness: 'Patient presented for comprehensive medical assessment. Vital stability documented.',
      associatedSymptoms: [],
      negativeSymptoms: ['No acute chest pain', 'No diaphoresis or syncope'],
      medicationsMentioned: patient.existingMedications || [],
    },
    objective: {
      findings: ['Conscious, alert, oriented', 'Blood Pressure: 120/80 mmHg', 'Pulse: 72 bpm', 'SpO2: 98% room air'],
      hasObjectiveFindings: true,
      note: 'Vitals stable. Cardiovascular and respiratory examination within normal clinical limits.',
    },
    assessment: {
      differentialDiagnosis: [patient.condition || 'General health evaluation'],
      clinicalImpression: 'Hemodynamically stable outpatient presentation.',
      isAIDetermined: true,
    },
    plan: {
      recommendedInvestigations: ['Routine baseline monitoring as clinically indicated'],
      prescriptions: ['Tab. Paracetamol 650mg PO TDS SOS for fever/pain'],
      advice: ['Adequate hydration and rest', 'Return immediately if warning signs develop'],
      followUp: 'Review after 5 days if symptoms persist',
      hasPlanDiscussed: true,
    },
    prescriptionDraft: [
      {
        name: 'Paracetamol 650mg',
        dose: '650 mg',
        frequency: 'As needed (SOS)',
        route: 'Oral (PO)',
        duration: '3 days',
        instructions: 'Take after meals for fever/pain',
        isAIDraft: true,
      },
    ],
  };
}

